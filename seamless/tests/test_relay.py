async def test_a_follower_relays_a_write_to_the_leader_with_the_callers_token(cluster, any_store):
    """SDD §12, §13.1, §25.6: a change sent to a follower runs on the leader as the caller's own.
    The leader authenticates the caller's token, checks its role and records the change - and a
    refusal - as for a direct request; the follower checks no token and passes the answer back as it
    came, with its own Date and Server alone. Of the caller's headers only Authorization,
    Content-Type and Accept-Encoding reach the leader - never a cookie or another one -, with
    X-Forwarded-For and the marker."""
    a = await cluster("seamless-a")
    b = await cluster("seamless-b")
    assert a.svc.leadership.leads() and not b.svc.leadership.leads()
    sent = {
        **cluster.auth(Role.admin),
        "Cookie": "session=kept-by-the-follower",
        "X-Request-Note": "kept by the follower",
        "Accept-Encoding": "identity",
    }
    async with httpx.AsyncClient(base_url=b.url, timeout=30) as caller:
        created = await caller.post("/api/v1/providers", json=SOURCE, headers=sent)
        refused = await caller.post(
            "/api/v1/providers", json=DESTINATION, headers=cluster.auth(Role.operator)
        )
        anonymous = await caller.post("/api/v1/providers", json=DESTINATION)
    assert created.status_code == 201, created.text
    assert created.json()["id"] == SOURCE["id"]
    for name in ("date", "server", "content-type", "x-frame-options"):
        assert len(created.headers.get_list(name)) == 1, f"{name} passed back once"
    assert (refused.status_code, refused.json()["error"]["code"]) == (403, "forbidden")
    assert (anonymous.status_code, anonymous.json()["error"]["code"]) == (401, "unauthorized")

    written = [
        (e.kind, e.actor)
        for e in any_store.events(limit=1000)
        if e.kind in ("provider.created", "auth.denied")
    ]
    assert written == [
        ("provider.created", "admin-user"),
        ("auth.denied", "operator-user"),
        ("auth.denied", "unauthenticated"),
    ]
    assert any_store.get("provider", SOURCE["id"], Provider).name == SOURCE["name"]
    with pytest.raises(NotFound):
        any_store.get("provider", DESTINATION["id"], Provider)

    relayed = relayed_to(a, "/api/v1/providers")
    assert [seen.method for seen in relayed] == ["POST"] * 3
    first = relayed[0]
    assert sorted(first.headers) == [
        "accept-encoding",
        "authorization",
        "content-length",
        "content-type",
        "host",
        "x-forwarded-for",
        "x-seamless-relayed",
    ]
    assert first.headers["authorization"] == sent["Authorization"]
    assert first.headers["content-type"] == "application/json"
    assert first.headers["accept-encoding"] == "identity"
    assert first.headers["x-seamless-relayed"] == "1"
    assert first.headers["host"] == f"127.0.0.1:{a.port}"
    assert "authorization" not in relayed[2].headers, "none sent, none added"
    assert not b.svc._auth_failures, "the follower checked no token"


async def test_a_follower_relays_the_event_stream_and_ends_it_when_the_leader_goes(
    cluster, any_store, monkeypatch, caplog
):
    """SDD §12, §25.6: the event stream asked of a follower is the leader's - its persisted events
    and its ephemeral ones as they come - and a quiet stream is never cut, though every other
    relayed request must end within its bound (half a second here). When the leader goes, the
    relayed stream ends; the client's reconnect with ?since= gets what it missed from the next
    leader."""
    monkeypatch.setattr("seamless_migrate.api.relay.RELAY_TIMEOUT_S", 0.5)
    a = await cluster("seamless-a", sse_heartbeat_s=60)
    b = await cluster("seamless-b", sse_heartbeat_s=60)
    viewer = cluster.auth(Role.viewer)
    first = await emit(a.svc.store, a.svc.bus, "plan.created", "one", plan_id="plan-relay")
    documents = a.svc.all_documents

    async def slow(kind: str, model: Any) -> list[Any]:
        await asyncio.sleep(5)
        return await documents(kind, model)

    noted = Timeouts()
    relay = httpx.AsyncClient(transport=noted, trust_env=False)
    monkeypatch.setattr(b.svc, "relay_client", relay)
    async with httpx.AsyncClient(base_url=b.url, timeout=httpx.Timeout(30, read=None)) as caller:
        # any other request: within the bound, else the leader does not answer
        monkeypatch.setattr(a.svc, "all_documents", slow)
        loop = asyncio.get_running_loop()
        began = loop.time()
        late = await caller.get("/api/v1/stats", headers=viewer)
        assert no_leader(late), late.text
        assert loop.time() - began < 3, "answered at the bound, not when the leader did"
        monkeypatch.setattr(a.svc, "all_documents", documents)
        path = f"/api/v1/events/stream?since={first.seq}"
        async with caller.stream("GET", path, headers=viewer) as answer:
            assert answer.status_code == 200
            assert answer.headers["content-type"].startswith("text/event-stream")
            frames = Frames(answer)
            try:
                second = await emit(
                    a.svc.store, a.svc.bus, "plan.updated", "two", plan_id="plan-relay"
                )
                assert (await frames.next())["id"] == str(second.seq)
                await asyncio.sleep(1.0)  # quiet for twice the bound of any other request
                await emit(
                    None,
                    a.svc.bus,
                    "migration.progress",
                    "50%",
                    migration_id="mig-relay",
                    persist=False,
                )
                live = await frames.next()
                assert (live["id"], live["event"]) == ("0", "migration.progress")
                assert not frames.done.is_set()
                await a.stop()  # the leader goes
                await asyncio.wait_for(frames.done.wait(), 15)
                assert frames.cut is None, f"the stream ended, not broke: {frames.cut!r}"
                unhandled = [r for r in caplog.records if "unhandled error" in r.getMessage()]
                assert unhandled == [], "the follower ended it as the SDD says, raising nothing"
            finally:
                await frames.close()
        assert relayed_to(a, "/api/v1/events/stream")[0].headers["x-seamless-relayed"] == "1"

        await until(lambda: b.svc.leadership.leads(), 15, "the follower's takeover")
        path = f"/api/v1/events/stream?since={second.seq}"
        async with caller.stream("GET", path, headers=viewer) as answer:
            frames = Frames(answer)
            try:
                missed = [(await frames.next())["event"] for _ in range(2)]
            finally:
                await frames.close()
    assert missed == ["leader.released", "leader.acquired"]
    # each relay connects within the retry period, 2 s at least, and no read of it is bounded
    # alone: a stream has no bound, any other request one bound for the whole of it
    within = {"connect": 2.0, "read": None, "write": None, "pool": 2.0}
    assert noted.seen == {"/api/v1/stats": within, "/api/v1/events/stream": within}
    await relay.aclose()


async def test_a_follower_answers_503_no_leader_while_no_replica_leads(
    cluster, any_store, monkeypatch
):
    """SDD §12, §25.6: a follower answers what it would relay with 503 no_leader and Retry-After: 2
    while no replica leads - nobody took the lease, it expired, or it names the follower itself,
    deposed before its lease lapsed -, never trying the lease's address then, and while the leader
    the lease names does not answer. Its health names who leads, if anyone, and its own routes
    answer as ever."""
    campaign = Lease.campaign
    monkeypatch.setattr(Lease, "campaign", lambda self, record=None: None)  # nobody here takes it
    b = await cluster("seamless-b", serve=False)
    viewer = cluster.auth(Role.viewer)
    relayed = (
        ("GET", "/api/v1/plans"),
        ("GET", "/api/v1/events/stream"),
        ("POST", "/api/v1/plans/plan-x/validate"),
    )

    async def refused(caller: httpx.AsyncClient, why: str) -> None:
        for method, path in relayed:
            answer = await caller.request(method, path, headers=viewer)
            assert no_leader(answer), (why, path, answer.status_code, answer.text)
            assert answer.headers["x-frame-options"] == "DENY", "the R-05 headers"

    async with Silent() as silent, b.client() as caller:
        await refused(caller, "nobody took the lease")
        body = (await caller.get("/api/v1/health")).json()
        assert body["leader"] == NOBODY
        assert body["orchestrator"] == NONE_RUNS

        phantom = Lease(any_store.engine, "seamless-a", silent.address, 30.0)
        assert campaign(phantom) == 1
        await refused(caller, "the leader does not answer")
        assert silent.connections == len(relayed), "it tried the leader each time"
        body = (await caller.get("/api/v1/health")).json()
        assert (body["leader"]["holder"], body["leader"]["epoch"]) == ("seamless-a", 1)
        assert body["orchestrator"] == BEFORE_START, "it wrote none since it took the lease"

        assert phantom.release(1)
        await refused(caller, "the lease expired")
        assert silent.connections == len(relayed), "an expired lease's address is not tried"
        body = (await caller.get("/api/v1/health")).json()
        assert body["leader"] == NOBODY and body["orchestrator"] == NONE_RUNS

        itself = Lease(any_store.engine, b.svc.leadership.holder, silent.address, 30.0)
        assert campaign(itself) == 2
        await refused(caller, "the lease names the follower itself")
        assert silent.connections == len(relayed), "never a relay to itself"
        body = (await caller.get("/api/v1/health")).json()
        assert body["leader"]["holder"] == b.svc.leadership.holder
        assert body["leader"]["leading"] is False

        ready = await caller.get("/api/v1/ready")
        assert (ready.status_code, ready.json()["status"]) == (200, "ok")


