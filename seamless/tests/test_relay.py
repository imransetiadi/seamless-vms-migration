def test_a_takeover_clears_the_orchestrator_health_the_last_leader_wrote(any_store):
    """SDD §11, §12: the leader's object rides on its renewals and, unhealthy, on writes of its own
    that renew nothing; a takeover clears it, so the new leader's term never reads as the last one's
    - its followers report an orchestrator before its start until its first renewal. A write of
    another replica's term writes nothing."""
    a = Lease(any_store.engine, "seamless-a", "192.0.2.10:8080", 1.0)
    b = Lease(any_store.engine, "seamless-b", "192.0.2.11:8080", 30.0)
    first = {"running": True, "last_tick_age_s": 0.4, "ticks": 12, "healthy": True}
    stalled = {"running": True, "last_tick_age_s": 42.0, "ticks": 12, "healthy": False}
    assert a.campaign() == 1 and a.read().health is None
    assert a.renew(1, health=first)
    renewed = a.read()
    assert renewed.health == first
    assert a.write_health(1, stalled)
    after = a.read()
    assert after.health == stalled
    assert (after.renewed_at, after.expires_at) == (renewed.renewed_at, renewed.expires_at)
    deadline = time.monotonic() + 15
    while not b.read().expired:  # by the database's clock, a second after the renewal
        assert time.monotonic() < deadline, "the lease never expired"
        time.sleep(0.05)
    assert b.campaign() == 2
    assert b.read().health is None, "the takeover cleared it"
    assert not a.write_health(1, first), "another replica's term"
    assert not a.renew(1, health=first)
    assert b.read().health is None
    assert b.renew(2, health=first) and b.read().health == first
