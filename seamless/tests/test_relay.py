    async with b.client(("192.0.2.77", 51000)) as caller, b.client(("192.0.2.78", 51001)) as other:
        for _ in range(3):
            assert (await caller.get("/api/v1/me", headers=spoofed)).status_code == 401
        locked = await caller.get("/api/v1/me", headers=wrong)
        assert (locked.status_code, locked.json()["error"]["code"]) == (429, "too_many_requests")
        assert (await other.get("/api/v1/me", headers=wrong)).status_code == 401
        welcome = await other.get("/api/v1/me", headers=cluster.auth(Role.viewer))
        assert welcome.json()["name"] == "viewer-user"
    relayed = relayed_to(a, "/api/v1/me")
