@dataclass(frozen=True)
class Seen:
    """A request as a replica's server handed it to the app: the client address uvicorn read."""

    method: str
    path: str
    client: str | None
    headers: dict[str, str]


class Spy:
    """An ASGI wrapper that notes every HTTP request a replica's server hands to its app."""

    def __init__(self, app: Any, seen: list[Seen]) -> None:
        self.app = app
        self.seen = seen

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if scope["type"] == "http":
            headers: dict[str, list[str]] = {}
            for name, value in scope["headers"]:
                headers.setdefault(name.decode("latin-1"), []).append(value.decode("latin-1"))
            client = scope.get("client")
            self.seen.append(
                Seen(
                    scope["method"],
                    scope["path"],
                    client[0] if client else None,
                    {name: ", ".join(values) for name, values in headers.items()},
                )
            )
        await self.app(scope, receive, send)


def bound_socket() -> socket.socket:
    """A socket bound to a free port of 127.0.0.1 and not listened on - a port no other test takes
    while it is held -, where nothing answers until a server listens on it (Linux refuses a
    connection there, macOS lets it wait for its timeout)."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind(("127.0.0.1", 0))
    return sock


@dataclass
class Replica:
    """One server replica: its app, the port its lease names and the requests its server got."""

    name: str
    app: Any
    sock: socket.socket
    seen: list[Seen] = field(default_factory=list)
    server: uvicorn.Server | None = None
    task: asyncio.Task[Any] | None = None
    _stop: asyncio.Event | None = None

    @property
    def svc(self) -> Any:
        return self.app.state.services

    @property
    def port(self) -> int:
        return int(self.sock.getsockname()[1])

    @property
    def url(self) -> str:
        return f"http://127.0.0.1:{self.port}"

    def client(self, caller: tuple[str, int] = ("192.0.2.40", 50400)) -> httpx.AsyncClient:
        """A caller at ``caller`` straight into the app, as the replica's server would hand its
        requests over - no socket, no answer streamed."""
        transport = httpx.ASGITransport(app=self.app, client=caller)
        return httpx.AsyncClient(transport=transport, base_url="http://testserver", timeout=30)

    async def health(self) -> dict[str, Any]:
        async with self.client() as caller:
            answer = await caller.get("/api/v1/health")
        assert answer.status_code == 200, answer.text
        return dict(answer.json())

    async def ready(self) -> httpx.Response:
        async with self.client() as caller:
            return await caller.get("/api/v1/ready")

    async def stop(self) -> None:
        """Stop the replica as SIGTERM does: its server ends its streams after a second, then its
        lifespan stops its orchestrator and releases its lease."""
        if self.task is None:
            return
        if self.server is not None:
            self.server.should_exit = True
        elif self._stop is not None:
            self._stop.set()
        task, self.task = self.task, None
        await asyncio.wait_for(task, 30)


class Cluster:
    """``await cluster(name, serve=True, **settings)``: a replica on the test's database, started
    and through its elector's first try - the first one started leads. Every one stops at the
    end."""

    def __init__(self, url: str, root: Path) -> None:
        self.url = url
        self.root = root
        self.tokens = write_tokens(root / "tokens.yaml")
        self.replicas: list[Replica] = []

    def auth(self, role: Role) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.tokens[role]}"}

    def settings(self, name: str, port: int, **kw: Any) -> Settings:
        lease_s = kw.pop("lease_s", SHORT_LEASE_S)
        data: dict[str, Any] = {
            "data_dir": self.root / name / "data",
            "db_url": self.url,
            "tokens_file": self.root / "tokens.yaml",
            "secrets_dir": self.root / name / "secrets",
            "tick_s": 0.05,
            "dashboard_dir": None,
            "demo": False,
            "port": port,
        }
        data.update(kw)
        # a lease of seconds, below the variable's bound (SDD §15.1)
        return Settings(**data).model_copy(update={"leader_lease_s": lease_s})

    async def __call__(
        self,
        name: str,
        *,
        serve: bool = True,
        sock: socket.socket | None = None,
        port: int | None = None,
        sse_heartbeat_s: float = 15.0,
        **kw: Any,
    ) -> Replica:
        """``port``, when given, is the one the replica's lease names instead of its own."""
        sock = sock or bound_socket()
        settings = self.settings(name, port or int(sock.getsockname()[1]), **kw)
        replica = Replica(name, create_app(settings, sse_heartbeat_s=sse_heartbeat_s), sock)
        self.replicas.append(replica)
        if serve:
            config = uvicorn.Config(
                Spy(replica.app, replica.seen),
                host="127.0.0.1",
                port=replica.port,
                log_level="warning",
                lifespan="on",
                proxy_headers=True,
                forwarded_allow_ips="127.0.0.1",
                timeout_graceful_shutdown=1,
            )
            replica.server = uvicorn.Server(config)
            replica.task = asyncio.create_task(replica.server.serve(sockets=[sock]))
            server = replica.server
            await until(lambda: server.started or replica.task.done(), 30, f"{name}'s start")
        else:
            started = asyncio.Event()
            replica._stop = asyncio.Event()

            async def live() -> None:
                assert replica._stop is not None
                async with replica.app.router.lifespan_context(replica.app):
                    started.set()
                    await replica._stop.wait()

            replica.task = asyncio.create_task(live())
            await until(lambda: started.is_set() or replica.task.done(), 30, f"{name}'s start")
        if replica.task.done():
            replica.task.result()  # its start failed: say why
        return replica

    async def close(self) -> None:
        for replica in reversed(self.replicas):
            with contextlib.suppress(Exception):
                await replica.stop()
        for replica in self.replicas:
            replica.svc.store.dispose()
            replica.sock.close()


