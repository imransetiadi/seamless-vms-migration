class Frames:
    """An event stream's frames as they come (heartbeats aside); ``done`` once it ended, and
    ``cut`` the error of a stream cut off rather than ended."""

    def __init__(self, response: httpx.Response) -> None:
        self.queue: asyncio.Queue[dict[str, str]] = asyncio.Queue()
        self.done = asyncio.Event()
        self.cut: Exception | None = None
        self.task = asyncio.create_task(self._read(response))

    async def _read(self, response: httpx.Response) -> None:
        buffer = ""
        try:
            async for chunk in response.aiter_text():
                buffer += chunk
                while "\n\n" in buffer:
                    frame, buffer = buffer.split("\n\n", 1)
                    if frame.startswith(":"):
                        continue
                    fields = dict(line.split(": ", 1) for line in frame.splitlines())
                    self.queue.put_nowait(fields)
        except httpx.HTTPError as exc:
            self.cut = exc
        finally:
            self.done.set()

    async def next(self, timeout: float = 15.0) -> dict[str, str]:
        return await asyncio.wait_for(self.queue.get(), timeout)

    async def close(self) -> None:
        self.task.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await self.task


class Silent:
    """A leader that does not answer: it notes each connection and closes it without a word."""

    def __init__(self) -> None:
        self.connections = 0
        self.server: asyncio.Server | None = None

    async def __aenter__(self) -> Silent:
        async def close(reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
            self.connections += 1
            writer.close()

        self.server = await asyncio.start_server(close, "127.0.0.1", 0)
        return self

    async def __aexit__(self, *exc: object) -> None:
        assert self.server is not None
        self.server.close()
        await self.server.wait_closed()

    @property
    def port(self) -> int:
        assert self.server is not None
        return int(self.server.sockets[0].getsockname()[1])

    @property
    def address(self) -> str:
        return f"127.0.0.1:{self.port}"


class Timeouts(httpx.AsyncBaseTransport):
    """The relay's transport, noting each request's timeouts before it sends it on: a connect
    that hangs - a leader's node gone - shows no difference on a test's loopback."""

    def __init__(self) -> None:
        self.inner = httpx.AsyncHTTPTransport()
        self.seen: dict[str, dict[str, Any]] = {}

    async def handle_async_request(self, request: httpx.Request) -> httpx.Response:
        self.seen[request.url.path] = dict(request.extensions["timeout"])
        return await self.inner.handle_async_request(request)

    async def aclose(self) -> None:
        await self.inner.aclose()


def relayed_to(replica: Replica, path: str) -> list[Seen]:
    return [seen for seen in replica.seen if seen.path == path]


def no_leader(answer: httpx.Response) -> bool:
    """Whether ``answer`` is a follower's 503 no_leader, Retry-After 2 (SDD §12)."""
    return (
        answer.status_code == 503
        and answer.headers.get("retry-after") == "2"
        and answer.json()["error"]["code"] == "no_leader"
    )


