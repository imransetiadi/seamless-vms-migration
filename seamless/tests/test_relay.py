async def test_the_leader_sees_the_callers_address_through_the_relay(cluster, any_store):
    """SDD §12, §13.1, §25.9: the follower extends X-Forwarded-For with the caller's address as it
    reads it, so the leader - whose uvicorn trusts the follower's address - records the caller in
    its audit and locks the caller out, never the follower and never an address the caller wrote
    into the header itself; another caller relayed by the same follower stays welcome."""
    a = await cluster("seamless-a", auth_lockout_per_minute=3)
    b = await cluster("seamless-b", serve=False, auth_lockout_per_minute=3)
    wrong = {"Authorization": "Bearer smg_not-a-token-of-this-installation"}
