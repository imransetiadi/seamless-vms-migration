"""scripts/seamless-doctor.sh and ``make seamless-doctor`` (SDD §17.1): a read-only check of a
contributor's machine against what the repository pins, each pin read from the file that sets
it. Run in a scratch tree against stub tools that record their calls: it installs nothing, never
prints a secret, fails for what ``make seamless-check`` or the stack targets need and only notes
the optional."""

