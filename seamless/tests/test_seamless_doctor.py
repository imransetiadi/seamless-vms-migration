def test_node_modules_older_than_the_lockfile_fails(tmp_path):
    """A pull that changed package-lock.json leaves node_modules behind until npm ci."""
    proc, _ = _run(tmp_path)
    assert proc.returncode == 0
    lock = tmp_path / "tree/dashboard/package-lock.json"
    later = (tmp_path / "tree/dashboard/node_modules/.package-lock.json").stat().st_mtime + 60
    os.utime(lock, (later, later))
    rerun = subprocess.run(
        ["bash", str(tmp_path / "tree/scripts/seamless-doctor.sh")],
        capture_output=True,
        text=True,
        env={
            "PATH": f"{tmp_path / 'bin'}:{tmp_path / 'base'}",
            "HOME": str(tmp_path / "home"),
            "STUB_LOG": str(tmp_path / "calls.log"),
        },
        timeout=60,
    )
    assert rerun.returncode == 1
    assert "older than package-lock.json" in rerun.stdout and "npm ci" in rerun.stdout


def test_an_engine_the_stack_targets_refuse_fails_with_their_message(tmp_path):
    message = "Docker Compose 2.12.2 is older than 2.20 (depends_on.required, SDD 17.1): upgrade it"
    make_says = f"{message}\nmake[1]: *** [Makefile:539: seamless-check-context] Error 1"
